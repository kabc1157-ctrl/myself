alter table public.journal_entries
  add column ai_feedback jsonb,
  add column analyzed_at timestamptz,
  add column ai_prompt_version text,
  add column analysis_attempted_at timestamptz,
  add column analysis_error text;

alter table public.journal_entries
  add constraint journal_entries_ai_feedback_object
    check (ai_feedback is null or jsonb_typeof(ai_feedback) = 'object'),
  add constraint journal_entries_analysis_state
    check (
      (ai_feedback is null and analyzed_at is null and ai_prompt_version is null)
      or
      (ai_feedback is not null and analyzed_at is not null and ai_prompt_version is not null)
    );

alter table public.routine_daily_reviews
  drop constraint if exists routine_daily_reviews_analysis_state,
  add column ai_prompt_version text,
  add column analysis_attempted_at timestamptz,
  add column analysis_error text,
  add constraint routine_daily_reviews_analysis_state
    check (
      (ai_feedback is null and analyzed_at is null and ai_prompt_version is null)
      or
      (ai_feedback is not null and analyzed_at is not null and ai_prompt_version is not null)
    );

create index journal_entries_pending_ai_analysis_idx
  on public.journal_entries (entry_date, user_id)
  where ai_feedback is null;

create index routine_daily_reviews_pending_ai_analysis_idx
  on public.routine_daily_reviews (review_date, user_id)
  where ai_feedback is null;

comment on column public.journal_entries.ai_feedback is
  'Structured daily insight generated by the private n8n workflow.';
comment on column public.routine_daily_reviews.ai_feedback is
  'Structured daily insight generated by the private n8n workflow.';
